CREATE TABLE game_players (
	game_id INT UNSIGNED NOT NULL,
	seat TINYINT UNSIGNED NOT NULL,
	is_bot BOOLEAN NOT NULL,
	was_replaced BOOLEAN NOT NULL,
	score SMALLINT NULL,
	placement TINYINT UNSIGNED NULL,
	is_winner BOOLEAN NOT NULL,
	field_points SMALLINT NOT NULL,
	challenge_penalty SMALLINT NOT NULL,
	sheep_count SMALLINT UNSIGNED NOT NULL,
	hand_size SMALLINT UNSIGNED NOT NULL,
	basic SMALLINT UNSIGNED NOT NULL,
	half_rainbow SMALLINT UNSIGNED NOT NULL,
	full_rainbow SMALLINT UNSIGNED NOT NULL,
	painted SMALLINT UNSIGNED NOT NULL,
	franken_heads SMALLINT UNSIGNED NOT NULL,
	franken_butts SMALLINT UNSIGNED NOT NULL,
	turns_taken SMALLINT UNSIGNED NOT NULL,
	sheep_built SMALLINT UNSIGNED NOT NULL,
	actions_played SMALLINT UNSIGNED NOT NULL,
	challenges_played SMALLINT UNSIGNED NOT NULL,
	challenges_won SMALLINT UNSIGNED NOT NULL,
	times_targeted SMALLINT UNSIGNED NOT NULL,
	PRIMARY KEY (game_id, seat),
	CONSTRAINT fk_players_game FOREIGN KEY (game_id) REFERENCES games(id) ON DELETE CASCADE
);
