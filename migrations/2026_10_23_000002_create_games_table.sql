CREATE TABLE games (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
	status ENUM('completed', 'abandoned') NOT NULL,
	started_at DATETIME(3) NOT NULL,
	ended_at DATETIME(3) NOT NULL,
	duration_ms INT UNSIGNED NOT NULL,
	player_count TINYINT UNSIGNED NOT NULL,
	human_count TINYINT UNSIGNED NOT NULL,
	bot_count TINYINT UNSIGNED NOT NULL,
	replaced_count TINYINT UNSIGNED NOT NULL,
	is_public BOOLEAN NOT NULL,
	turns SMALLINT UNSIGNED NOT NULL,
	final_round_reached BOOLEAN NOT NULL,
	winner_seat TINYINT UNSIGNED NULL,
	winner_is_bot BOOLEAN NULL,
	winning_score SMALLINT NULL,
	was_tiebreak BOOLEAN NULL,
	tied_count TINYINT UNSIGNED NULL,
	deck_left SMALLINT UNSIGNED NOT NULL,
	discard_size SMALLINT UNSIGNED NOT NULL,
	sheep_built SMALLINT UNSIGNED NOT NULL,
	actions_played SMALLINT UNSIGNED NOT NULL,
	bodyswaps SMALLINT UNSIGNED NOT NULL,
	challenges_played SMALLINT UNSIGNED NOT NULL,
	coin_flips SMALLINT UNSIGNED NOT NULL,
	reflips SMALLINT UNSIGNED NOT NULL,
	event_count INT UNSIGNED NOT NULL,
	INDEX idx_games_started (started_at),
	INDEX idx_games_status (status)
);
